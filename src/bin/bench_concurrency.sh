#!/usr/bin/env bash
# Benchmark capture-point concurrency at 3, 4, 6, and 9 contexts.
#
# Prerequisites:
#   cargo build --release
#
# Usage:
#   bash src/bin/bench_concurrency.sh [--warmup-runs N] [--measure-runs N]
#
# Output: appends to .scratch/capture-backend-fallback/concurrency-sweep.md

set -euo pipefail

BINARY="${BINARY:-./target/release/vimg}"
VIDEO="${VIDEO:-./sample/input.mkv}"
OUTDIR="${OUTDIR:-/tmp/vimg-concurrency-sweep}"
WARMUP_RUNS="${WARMUP_RUNS:-2}"
MEASURE_RUNS="${MEASURE_RUNS:-5}"

REPORT=".scratch/capture-backend-fallback/concurrency-sweep.md"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --warmup-runs) WARMUP_RUNS="$2"; shift 2 ;;
    --measure-runs) MEASURE_RUNS="$2"; shift 2 ;;
    *)
      echo "Unknown option: $1"
      exit 1
      ;;
  esac
done

mkdir -p "$OUTDIR" "$(dirname "$REPORT")"

CONCURRENCIES=(3 4 6 9)

# Header
{
  echo ""
  echo "## FFmpeg Backend"
  echo ""
  echo "**Date:** $(date -u +"%Y-%m-%d %H:%M UTC")"
  echo "**Warmup:** $WARMUP_RUNS runs, **Measure:** $MEASURE_RUNS runs"
  echo ""
  echo "| T | Wall (s) | User CPU (s) | Max RSS (MB) |"
  echo "|---|---:|---:|---:|"
} >> "$REPORT"

for T in "${CONCURRENCIES[@]}"; do
  local output="$OUTDIR/bench-ffmpeg-T${T}.avif"

  # Warmup
  for _ in $(seq 1 "$WARMUP_RUNS"); do
    "$BINARY" vcs -c3 -H160 -n9 -T"$T" "$VIDEO" --output "$output" > /dev/null 2>&1 || true
  done

  # Measure
  local wall_sum=0 user_sum=0 rss_sum=0
  for _ in $(seq 1 "$MEASURE_RUNS"); do
    local time_file="$OUTDIR/time-ffmpeg-T${T}-${RANDOM}.txt"
    /usr/bin/time -lp "$BINARY" vcs -c3 -H160 -n9 -T"$T" "$VIDEO" --output "$output" \
      > /dev/null 2> "$time_file" || true

    local wall
    wall=$(grep '^real' "$time_file" | awk '{print $NF}' || echo "0")
    wall_sum=$(echo "$wall_sum + $wall" | bc)

    local user_cpu
    user_cpu=$(grep '^user' "$time_file" | awk '{print $NF}' || echo "0")
    user_sum=$(echo "$user_sum + $user_cpu" | bc)

    local max_rss
    max_rss=$(grep 'maximum resident set size' "$time_file" | grep -oE '[0-9]+' || echo "0")
    rss_sum=$(echo "$rss_sum + $max_rss" | bc)
  done

  local avg_wall avg_user avg_rss_mb
  avg_wall=$(echo "scale=2; $wall_sum / $MEASURE_RUNS" | bc)
  avg_user=$(echo "scale=2; $user_sum / $MEASURE_RUNS" | bc)
  avg_rss_mb=$(echo "scale=1; $rss_sum / $MEASURE_RUNS / 1048576" | bc)

  echo "| $T | $avg_wall | $avg_user | $avg_rss_mb |" >> "$REPORT"
done

echo "" >> "$REPORT"
echo "_Generated by \`src/bin/bench_concurrency.sh\`_" >> "$REPORT"
echo "Report: $REPORT"
